#!/usr/bin/env python3
"""Build/check Claude desktop's ZIP from the one maintained AgentBay SKILL.md."""
import argparse
import io
import json
import pathlib
import zipfile
import installer
from example_bundle import safe_path, digest

ROOT = pathlib.Path(__file__).resolve().parent.parent
ARCHIVE = pathlib.Path('downloads/agentbay-skill-installer.zip')
CHECKSUM = pathlib.Path(str(ARCHIVE)+'.sha256')
MARKER = b'Generated by scripts/skill_bundle.py from the maintained SKILL.md.'
ENTRY = 'agentbay-skill-installer/SKILL.md'

def payload(root):
    raw = safe_path(root, installer.RELATIVE).read_bytes()
    installer.validate(raw)
    description=next(line[len('description: '):] for line in raw.decode().splitlines() if line.startswith('description: '))
    if len(description)>200:raise ValueError('Claude desktop description must be at most 200 characters')
    stream = io.BytesIO()
    with zipfile.ZipFile(stream, 'w', compression=zipfile.ZIP_STORED) as archive:
        archive.comment = MARKER
        entry = zipfile.ZipInfo(ENTRY, date_time=(1980,1,1,0,0,0))
        entry.create_system = 3
        entry.external_attr = 0o100644 << 16
        archive.writestr(entry, raw)
    return stream.getvalue()

def checksum(raw):
    return (digest(raw)+'  '+ARCHIVE.name+'\n').encode()

def check(root=ROOT):
    root = root.resolve()
    raw = payload(root)
    if safe_path(root, ARCHIVE).read_bytes()!=raw or safe_path(root, CHECKSUM).read_bytes()!=checksum(raw):
        raise ValueError('Skill ZIP/checksum is stale; run python3 scripts/skill_bundle.py build')
    return {'archive':str(ARCHIVE),'sha256':digest(raw),'bytes':len(raw),'source_sha256':digest(safe_path(root,installer.RELATIVE).read_bytes()),'result':'passed'}

def build(root=ROOT):
    root = root.resolve()
    raw = payload(root)
    target,sidecar = safe_path(root,ARCHIVE),safe_path(root,CHECKSUM)
    previous = None
    if target.exists():
        previous = target.read_bytes()
        with zipfile.ZipFile(io.BytesIO(previous)) as archive:
            if archive.comment!=MARKER:raise ValueError('Preserving an unowned ZIP')
    if sidecar.exists() and (previous is None or sidecar.read_bytes()!=checksum(previous)):
        raise ValueError('Preserving a modified or unowned checksum')
    for path in (target,sidecar):
        temporary = path.with_name('.'+path.name+'.tmp')
        if temporary.exists() or temporary.is_symlink():raise ValueError('Preserving an existing temporary output')
    for path,content in ((target,raw),(sidecar,checksum(raw))):
        path.parent.mkdir(parents=True,exist_ok=True)
        temporary = path.with_name('.'+path.name+'.tmp')
        with temporary.open('xb') as output:output.write(content)
        temporary.replace(path)
    return check(root)

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command',choices=['build','check'])
    args=parser.parse_args()
    print(json.dumps(build() if args.command=='build' else check(),indent=2))

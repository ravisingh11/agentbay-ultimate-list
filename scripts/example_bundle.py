#!/usr/bin/env python3
"""Build or check the small, reproducible Cloudflare first-use download."""
import argparse
import hashlib
import io
import json
import pathlib
import zipfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
PREFIX = 'agentbay-cloudflare-demo'
ARCHIVE = pathlib.Path('docs/examples/cloudflare-worker.zip')
CHECKSUM = pathlib.Path(str(ARCHIVE)+'.sha256')
MARKER = b'Generated by scripts/example_bundle.py; edit the source example.'
SOURCES = {name: 'docs/examples/cloudflare-worker/'+name for name in (
    '.gitignore', 'package.json', 'package-lock.json', 'wrangler.jsonc',
    'src/index.js', 'test/worker.test.js')}
SOURCES['LICENSE'] = 'LICENSE'


def digest(raw):
    return hashlib.sha256(raw).hexdigest()


def safe_path(root, relative):
    target = root/relative
    for part in [target]+list(target.parents):
        if part.is_symlink():
            raise ValueError('Refusing symlink: '+str(part))
        if part == root:
            break
    return target


def payload(root=ROOT):
    root = root.resolve()
    files = {}
    manifest = {'schema_version': 1,
                'source_repository': 'https://github.com/ravisingh11/agentbay-ultimate-list',
                'files': {}}
    for name, relative in sorted(SOURCES.items()):
        path = safe_path(root, relative)
        if not path.is_file():
            raise ValueError('Missing regular source file: '+relative)
        raw = path.read_bytes()
        files[name] = raw
        manifest['files'][name] = {'source_path': relative, 'bytes': len(raw), 'sha256': digest(raw)}
    files['source-manifest.json'] = (json.dumps(manifest, indent=2, sort_keys=True)+'\n').encode()
    stream = io.BytesIO()
    with zipfile.ZipFile(stream, 'w', compression=zipfile.ZIP_STORED) as archive:
        archive.comment = MARKER
        for name, raw in sorted(files.items()):
            entry = zipfile.ZipInfo(PREFIX+'/'+name, date_time=(1980, 1, 1, 0, 0, 0))
            entry.create_system = 3
            entry.external_attr = 0o100644 << 16
            archive.writestr(entry, raw)
    return stream.getvalue()


def checksum(raw):
    return (digest(raw)+'  '+ARCHIVE.name+'\n').encode()


def check(root=ROOT):
    root = root.resolve()
    raw = payload(root)
    if safe_path(root, ARCHIVE).read_bytes() != raw:
        raise ValueError('Example archive is stale; run scripts/example_bundle.py build')
    if safe_path(root, CHECKSUM).read_bytes() != checksum(raw):
        raise ValueError('Example checksum differs from the archive')
    return {'archive': ARCHIVE.as_posix(), 'bytes': len(raw), 'sha256': digest(raw),
            'source_files': len(SOURCES), 'result': 'passed'}


def build(root=ROOT):
    root = root.resolve()
    raw = payload(root)
    target = safe_path(root, ARCHIVE)
    sidecar = safe_path(root, CHECKSUM)
    previous = None
    if target.exists():
        previous = target.read_bytes()
        try:
            with zipfile.ZipFile(io.BytesIO(previous)) as existing:
                if existing.comment != MARKER:
                    raise ValueError('Preserving an unowned example archive')
        except zipfile.BadZipFile as error:
            raise ValueError('Preserving an unrecognized example archive') from error
    if sidecar.exists() and (previous is None or sidecar.read_bytes() != checksum(previous)):
        raise ValueError('Preserving a modified or unowned example checksum')
    outputs = {target: raw, sidecar: checksum(raw)}
    for path in outputs:
        temporary = path.with_name('.'+path.name+'.tmp')
        if temporary.exists() or temporary.is_symlink():
            raise ValueError('Preserving an existing temporary file: '+str(temporary))
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        temporary = path.with_name('.'+path.name+'.tmp')
        with temporary.open('xb') as output:
            output.write(content)
        temporary.replace(path)
    return check(root)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['build', 'check'])
    args = parser.parse_args()
    print(json.dumps(build() if args.command == 'build' else check(), indent=2))


if __name__ == '__main__':
    main()
